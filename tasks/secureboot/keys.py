"""
Secure Boot Key Management Interface
Orchestrates key generation, inspection, export, backup, and restoration via sbctl.
Follows strict safety rules: never overwrites or deletes keys automatically.
"""

import json
import os
import shutil
import subprocess
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from tasks.secureboot.config import (
    BACKUP_DIR,
    SB_DATABASES,
    SB_DB_DESCRIPTIONS,
    SBCTL_DB_DIR,
    SBCTL_KEYS_DIR,
)
from tasks.secureboot.utils import (
    dir_exists_privileged,
    file_exists_privileged,
    find_files_privileged,
    run_privileged,
)


def do_keys_exist() -> bool:
    """Checks whether custom Secure Boot keys exist on disk (generated by sbctl)."""
    # 1. Check sbctl status --json
    if shutil.which("sbctl"):
        try:
            out = subprocess.check_output(
                ["sbctl", "status", "--json"],
                stderr=subprocess.DEVNULL,
                text=True,
                timeout=5,
            )
            data = json.loads(out)
            if bool(data.get("installed", False)):
                return True
        except Exception:
            pass

    # 2. Check filesystem directories (/var/lib/sbctl/keys and /usr/share/secureboot/keys)
    for cand_dir in (SBCTL_KEYS_DIR, Path("/var/lib/sbctl/keys"), Path("/usr/share/secureboot/keys")):
        if dir_exists_privileged(cand_dir):
            has_pk = len(find_files_privileged(cand_dir / "PK", "*")) > 0
            has_db = len(find_files_privileged(cand_dir / "db", "*")) > 0
            if has_pk or has_db:
                return True

    return False


def inspect_key_inventory() -> Dict[str, Dict[str, Any]]:
    """
    Inspects available keys and certificates in sbctl key storage.
    Returns status, file paths, and presence for each database (PK, KEK, db).
    Never reads or exposes private key contents.
    """
    inventory: Dict[str, Dict[str, Any]] = {}

    # Check active directory or fallback
    keys_dir = SBCTL_KEYS_DIR
    if not dir_exists_privileged(keys_dir):
        for alt in (Path("/var/lib/sbctl/keys"), Path("/usr/share/secureboot/keys")):
            if dir_exists_privileged(alt):
                keys_dir = alt
                break

    for db_name in SB_DATABASES:
        db_path = keys_dir / db_name
        cert_path: Optional[Path] = None
        key_path: Optional[Path] = None

        if dir_exists_privileged(db_path):
            files = find_files_privileged(db_path, "*")
            for f in files:
                if f.suffix in (".crt", ".pem", ".der"):
                    cert_path = f
                elif f.suffix in (".key", ".priv"):
                    key_path = f

        has_cert = cert_path is not None and file_exists_privileged(cert_path)
        has_key = key_path is not None and file_exists_privileged(key_path)

        # Check permissions on private key if present
        key_perm_secure = False
        if has_key and key_path:
            try:
                mode = key_path.stat().st_mode & 0o777
                key_perm_secure = (mode & 0o077) == 0
            except (PermissionError, OSError):
                # If unprivileged user can't stat/read it, it's definitely protected from unprivileged access
                key_perm_secure = True

        inventory[db_name] = {
            "name": db_name,
            "description": SB_DB_DESCRIPTIONS.get(db_name, ""),
            "has_certificate": has_cert,
            "has_private_key": has_key,
            "certificate_path": str(cert_path) if cert_path else None,
            "private_key_path": str(key_path) if key_path else None,
            "private_key_secure": key_perm_secure,
            "ready": has_cert and has_key,
        }

    return inventory


def create_keys(force: bool = False) -> Tuple[bool, str]:
    """
    Generates a new set of Secure Boot signing keys using `sbctl create-keys`.
    SAFETY: Fails if keys already exist unless explicitly authorized.
    """
    if do_keys_exist() and not force:
        return False, "Existing keys detected. Generation aborted to prevent overwriting."

    if not shutil.which("sbctl"):
        return False, "sbctl is not installed."

    from core import auth
    if not auth.is_sudo_active():
        if not auth.request_sudo_auth("Generating Secure Boot Keys"):
            return False, "Sudo authorization cancelled or required."

    try:
        from core.logger import logger
        code, _ = logger.run_cmd(["sudo", "sbctl", "create-keys"], check=False)
        if code == 0:
            # Enforce 0600 on private keys
            _secure_key_permissions()
            return True, "Secure Boot keys generated successfully."
        else:
            return False, f"sbctl create-keys exited with code {code}."
    except Exception as e:
        return False, f"Failed to execute sbctl create-keys: {e}"


def _secure_key_permissions() -> None:
    """Ensures private keys under sbctl have 0600 permissions and directory has 0700."""
    try:
        from core.logger import logger
        for cand in (SBCTL_KEYS_DIR, Path("/var/lib/sbctl/keys"), Path("/usr/share/secureboot/keys")):
            logger.run_cmd(["sudo", "chmod", "700", str(cand)], check=False)
            logger.run_cmd(["sudo", "chmod", "-R", "go-rwx", str(cand)], check=False)
    except Exception:
        pass


def export_certificates(dest_dir: Path) -> Tuple[bool, List[str]]:
    """
    Exports public certificates (never private keys) to dest_dir.
    Useful for MOK enrollment or external inspection.
    """
    exported: List[str] = []
    dest_dir.mkdir(parents=True, exist_ok=True)

    inv = inspect_key_inventory()
    for db_name, data in inv.items():
        cert_p = data.get("certificate_path")
        if cert_p:
            cp = Path(cert_p)
            if file_exists_privileged(cp):
                target = dest_dir / f"{db_name}.pem"
                try:
                    # Try direct copy, falling back to privileged cp if parent is 0700
                    shutil.copy2(str(cp), str(target))
                    exported.append(str(target))
                except (PermissionError, OSError):
                    code, _, _ = run_privileged(["cp", str(cp), str(target)])
                    if code == 0:
                        exported.append(str(target))

    return len(exported) > 0, exported


def inspect_enrolled_keys() -> List[Dict[str, Any]]:
    """
    Lists keys currently enrolled in firmware using `sbctl list-enrolled-keys`.
    """
    enrolled: List[Dict[str, Any]] = []
    if not shutil.which("sbctl"):
        return enrolled

    try:
        out = subprocess.check_output(
            ["sbctl", "list-enrolled-keys"],
            stderr=subprocess.DEVNULL,
            text=True,
            timeout=5,
        )
        current_db = "Unknown"
        for line in out.splitlines():
            line_s = line.strip()
            if not line_s:
                continue
            if line_s.endswith(":") or line_s in SB_DATABASES:
                current_db = line_s.replace(":", "")
            else:
                enrolled.append({
                    "database": current_db,
                    "description": line_s,
                })
    except Exception:
        pass
    return enrolled

